test('a second tab cannot overwrite local edits and can take over after the writer closes', async ({ page, context }) => {
  await page.goto('notes/')
  await page.getByRole('textbox', { name:'Notes', exact:true }).fill('Contenu conservé entre onglets')
  await expect(page.locator('.sync')).toHaveText('Enregistré sur cet appareil')
  const other = await context.newPage()
  await other.goto('notes/')
  await expect(other.locator('.sync')).toContainText('Lecture seule')
  await expect(other.getByRole('button', { name:'Nouvelle note', exact:true }).first()).toBeDisabled()
  await expect(other.locator('.rich')).toContainText('Contenu conservé entre onglets')
  await page.close()
  await other.getByRole('button', { name:'Réessayer', exact:true }).click()
  const editor = other.getByRole('textbox', { name:'Notes', exact:true })
  await expect(editor).toHaveValue('Contenu conservé entre onglets')
  await editor.fill('Modification du nouvel onglet')
  await expect(other.locator('.sync')).toHaveText('Enregistré sur cet appareil')
  await other.reload()
  await expect(editor).toHaveValue('Modification du nouvel onglet')
})
test('retry persists the open note after a transient IndexedDB write failure', async ({ page }) => {
  await page.goto('notes/')
  await expect(page.locator('.sync')).toHaveText('Enregistré sur cet appareil')
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    let fail = true
    IDBObjectStore.prototype.put = function(...args: Parameters<typeof put>) { if (this.name === 'books' && fail) { fail = false; throw new DOMException('Test quota failure','QuotaExceededError') } return put.apply(this,args) }
  })
  const editor = page.getByRole('textbox', { name:'Notes', exact:true })
  await editor.fill('À conserver malgré une erreur locale')
  await expect(page.locator('.sync')).toContainText('Sauvegarde impossible')
  await page.getByRole('button', { name:'Réessayer', exact:true }).click()
  await expect(page.locator('.sync')).toHaveText('Enregistré sur cet appareil')
  await page.reload()
  await expect(editor).toHaveValue('À conserver malgré une erreur locale')
})
