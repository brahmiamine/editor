test('installed shell reopens offline and saves multiple guest notes', async ({ page, context }) => {
  await page.goto('notes/')
  const editor = page.getByRole('textbox', { name: 'Notes', exact: true })
  await editor.fill('Disponible hors connexion')
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(editor).toHaveValue('Disponible hors connexion')
  await page.getByRole('button', { name: 'Nouvelle note', exact: true }).first().click()
  await editor.fill('Deuxième note hors connexion')
  await expect(page.locator('.sync')).toHaveText('Hors connexion — enregistré sur cet appareil')
  await page.reload()
  await expect(editor).toHaveValue('Deuxième note hors connexion')
  await expect(page.locator('.note-row')).toHaveCount(2)
  await context.setOffline(false)
})

